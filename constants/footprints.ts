export type FootprintCity = {
  code: string;
  name: string;
};

export type FootprintProvince = {
  code: string;
  name: string;
  cities: FootprintCity[];
};

const cityList = (provinceCode: string, names: string[]): FootprintCity[] => names.map((name, index) => ({
  code: provinceCode + '-' + String(index + 1).padStart(2, '0'),
  name,
}));

const province = (code: string, name: string, cities: string[]): FootprintProvince => ({ code, name, cities: cityList(code, cities) });

